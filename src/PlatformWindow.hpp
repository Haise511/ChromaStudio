#pragma once
// ChromaStudio Engine · Phase 1 · Win32 platform window.
//
// Spec references (production_engine_spec.md):
//   §2  Per-Monitor V2 before the first HWND. Client DIP u = clientPx·96/dpi. WM_DPICHANGED accepts
//       the suggested rectangle and publishes DPI and framebuffer size as one generation; an active
//       stroke is finished with its last confirmed packet before the geometry changes.
//   §3  Pen through WM_POINTERDOWN/UPDATE/UP. GetPointerPenInfoHistory is copied immediately and
//       reversed (the API returns newest first). penMask gates every axis; p = clamp(pressure/1024,
//       0, 1), or 1 when the axis is absent. Tilt and twist degrees become radians. The eraser end is
//       latched from Down to Up. Time comes from PerformanceCount/QPC with the unwrapped dwTime as a
//       fallback. History is de-duplicated. Mouse messages promoted from pen or touch are dropped;
//       the plain mouse uses WM_*BUTTON*, WM_MOUSEMOVE and SetCapture.
//   §11 Initial client 1440×900 DIP clamped to the monitor work area, 640×400 minimum. Capture loss,
//       deactivation and close cancel the active gesture; the end flag is set before ReleaseCapture
//       so a normal release never produces a second action.
//
// Coordinates are continuous: physical pixel i covers [i, i+1). Integer sources (the mouse, or a pen
// whose HIMETRIC grid cannot be mapped) are reported at pixel centres, i + 0.5.
//
// The window reports every contact. Choosing which contact owns a stroke (§11.2) is the editor's job.
// Listener callbacks run inside the window procedure and must not pump messages.

